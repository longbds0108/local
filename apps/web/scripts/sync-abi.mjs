// Regenerates lib/escrow-abi.ts from the Foundry build output.
// Usage: (cd ../../contracts && forge build) && npm run abi
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = join(here, "../../../contracts/out/HedgoraEscrow.sol/HedgoraEscrow.json");
const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
const out = join(here, "../lib/escrow-abi.ts");
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/sync-abi.mjs from contracts/out — do not edit by hand.\nexport const ESCROW_ABI = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${abi.length} entries)`);
