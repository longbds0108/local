/** Merchant names are real business names, except the shared pool, which is ours to translate. */
export function merchantName(t: Dict, m: { id?: string | null; name?: string | null } | null | undefined): string {
  if (!m) return "";
  return m.id === "m_partner" ? t.partnerPool : (m.name ?? "");
}
